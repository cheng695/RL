"""Generate a reversible pair-averaged leg-mass experiment, without Isaac Sim."""

from pathlib import Path
import math
import xml.etree.ElementTree as ET


XML_DIR = (Path(__file__).resolve().parents[1] / "source/my_robot_lab/my_robot_lab/assets/robots"
           / "UZ05_MJCF_real_params/xmls")


def generate():
    source = XML_DIR / "uz05_isaac.xml"
    output = XML_DIR / "uz05_isaac_equal_leg_masses.xml"
    tree = ET.parse(source)
    root = tree.getroot()
    bodies = {body.attrib["name"]: body for body in root.iter("body")}
    original_total = sum(float(x.attrib["mass"]) for x in root.iter("inertial"))
    before = [0.0, 0.0]
    after = 0.0
    for left_name, left in bodies.items():
        if not left_name.startswith("left_") or left.find("inertial") is None:
            continue
        right = bodies["right_" + left_name[5:]]
        inertials = [left.find("inertial"), right.find("inertial")]
        if any(x is None for x in inertials):
            raise ValueError(f"Missing paired inertial for {left_name}")
        masses = [float(x.attrib["mass"]) for x in inertials]
        if not all(math.isfinite(m) and m > 0 for m in masses):
            raise ValueError(f"Invalid mass for {left_name}")
        mean = sum(masses) / 2
        for i, (inertial, mass) in enumerate(zip(inertials, masses)):
            before[i] += mass
            inertia_key = "fullinertia" if "fullinertia" in inertial.attrib else "diaginertia"
            inertia = [float(v) * mean / mass for v in inertial.attrib[inertia_key].split()]
            inertial.set("mass", format(mean, ".17g"))
            inertial.set(inertia_key, " ".join(format(v, ".17g") for v in inertia))
        after += mean
        print(f"{left_name}: L={masses[0]:.9f}, R={masses[1]:.9f} -> each={mean:.9f} kg")
    total = sum(float(x.attrib["mass"]) for x in root.iter("inertial"))
    if not math.isclose(total, original_total, rel_tol=0, abs_tol=1e-9):
        raise ValueError("Pair averaging changed the total robot mass")
    root.insert(0, ET.Comment("Generated by equalize_uz05_leg_masses.py: pair-average masses; scale inertia; preserve CoM."))
    tree.write(output, encoding="utf-8", xml_declaration=True)
    print(f"Leg assemblies before: L={before[0]:.9f}, R={before[1]:.9f}; after each={after:.9f} kg")
    print(f"Robot total: {total:.9f} kg; output: {output}")


if __name__ == "__main__":
    generate()
